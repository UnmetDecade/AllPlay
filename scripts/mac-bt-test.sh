#!/usr/bin/env bash
# ============================================================================
# mac-bt-test.sh — run core_selftest --bt in the Mac's **desktop session** (M2 on-device test)
# ============================================================================
# Why so roundabout: macOS 27's Bluetooth privacy (TCC) only trusts processes in a GUI session; processes arrived at over ssh
# are silently denied when enumerating/querying Bluetooth. Approach: generate a .command → launch it with `open -a Terminal`
# (permission belongs to Terminal), write the output to disk and read it back.
#
# Usage (run in the container; SSID may be empty, in which case testing stops before Wi-Fi configuration):
#   scripts/mac-bt-test.sh <WiFi name> [WiFi password] [device name filter=iPhone]
# Afterwards:
#   ssh -p 2223 hewei@127.0.0.1 'tail -f /tmp/allplay-bt.log'   # follow live
set -euo pipefail

SSID="${1-}"
PASS="${2:-}"
DEV="${3:-iPhone}"

: "${ALLPLAY_HOST:=hewei@127.0.0.1}"
: "${ALLPLAY_SSH_PORT:=2223}"
KEY="${ALLPLAY_SSH_KEY:-/root/.ssh/id_allplay}"
HOST="$ALLPLAY_HOST"
SSH_OPTS="-i ${KEY} -p ${ALLPLAY_SSH_PORT} -o StrictHostKeyChecking=no -o UserKnownHostsFile=/root/.ssh/known_hosts_remote"
LOG=/tmp/allplay-bt.log

# ---- Generate the .command (locally, then scp, to avoid quoting hell) ----
tmp="$(mktemp)"
cat > "$tmp" <<EOF
#!/bin/bash
# Generated by scripts/mac-bt-test.sh (runs in the Mac desktop session)
cd "\${HOME}/AllPlay" || exit 1
echo "==== \$(date) started ====" > ${LOG}
echo "== Environment ==" >> ${LOG}
./build/core_selftest --bt --bt-device '${DEV}' --ssid '${SSID}' --wifi-pass '${PASS}' \
    --identity identity --screen 1280x720 >> ${LOG} 2>&1
echo "==== process exited (code=\$?) ====" >> ${LOG}
EOF
chmod +x "$tmp"
cp "$tmp" /tmp/run-bt.command.local

scp -i "$KEY" -P "$ALLPLAY_SSH_PORT" \
    -o StrictHostKeyChecking=no -o UserKnownHostsFile=/root/.ssh/known_hosts_remote \
    "$tmp" "${HOST}:AllPlay/run-bt.command" >/dev/null
rm -f "$tmp"

echo "== Launch in the Mac desktop session (TCC belongs to Terminal) =="
ssh $SSH_OPTS "$HOST" "chmod +x ~/AllPlay/run-bt.command && open -a Terminal ~/AllPlay/run-bt.command && echo Launched"

echo "== Wait 8 seconds, then read the log back =="
sleep 8
ssh $SSH_OPTS "$HOST" "cat ${LOG} 2>/dev/null || echo '(no output yet)'"
echo
echo "== Watch anytime afterwards: =="
echo "   ssh -i ${KEY} -p ${ALLPLAY_SSH_PORT} ${HOST} 'tail -40 ${LOG}'"
